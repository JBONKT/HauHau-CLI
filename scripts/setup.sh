#!/bin/sh
# Hauhau setup for macOS/Linux. Idempotent: safe to re-run after a pull or a
# Python upgrade. Verifies the environment, builds the venv, installs the
# package, and drops a launcher on PATH.
set -eu

REPO="$(cd "$(dirname "$0")/.." && pwd)"
PYTHON="${PYTHON:-python3}"
LAUNCHER_DIR="${LAUNCHER_DIR:-$HOME/.local/bin}"
DATA_DIR="$HOME/.hauhau"

say() { printf '%s\n' "$*"; }
die() { printf 'setup: %s\n' "$*" >&2; exit 1; }

say "hauhau setup - repo $REPO"

# --- 1. python -------------------------------------------------------------
command -v "$PYTHON" >/dev/null 2>&1 || die "python3 not found. Install it: brew install python@3.12"
"$PYTHON" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 11) else 1)' 2>/dev/null \
    || die "$($PYTHON --version 2>&1) is too old; 3.11+ is required"
say "  python: $($PYTHON --version 2>&1)"

# --- 2. llama-server -------------------------------------------------------
if ! command -v llama-server >/dev/null 2>&1; then
    die "llama-server not found. Install it: brew install llama.cpp
       (or set [model] llama_server in config.toml to an absolute path)"
fi
say "  llama-server: $(command -v llama-server) $(llama-server --version 2>&1 | head -1)"

# --- 3. model --------------------------------------------------------------
GGUF="$(sed -n 's/^[[:space:]]*gguf[[:space:]]*=[[:space:]]*"\(.*\)"/\1/p' "$REPO/config.toml" 2>/dev/null | head -1)"
if [ -z "$GGUF" ]; then
    die "no [model] gguf set in $REPO/config.toml"
fi
if [ ! -f "$GGUF" ]; then
    say "  model: MISSING at $GGUF"
    say "  found candidates:"
    find "$HOME/modeller/gguf" "$HOME/models" "$HOME/.cache/llama.cpp" -maxdepth 2 -name '*.gguf' 2>/dev/null \
        | sed 's/^/    /' | head -5
    die "point [model] gguf at an existing .gguf file (or set HAUHAU_GGUF)"
fi
say "  model: $GGUF ($(( $(stat -f%z "$GGUF" 2>/dev/null || stat -c%s "$GGUF") / 1024 / 1024 )) MB)"

# --- 4. venv ---------------------------------------------------------------
if [ ! -x "$REPO/.venv/bin/python" ]; then
    say "  creating venv"
    "$PYTHON" -m venv "$REPO/.venv"
fi
"$REPO/.venv/bin/python" -m pip install -q --upgrade pip
say "  installing hauhau (editable, with dev extras)"
"$REPO/.venv/bin/python" -m pip install -q -e "$REPO[dev]"

# --- 5. runtime dirs -------------------------------------------------------
mkdir -p "$DATA_DIR/logs" "$DATA_DIR/brain" "$DATA_DIR/sessions"

# --- 6. launcher -----------------------------------------------------------
mkdir -p "$LAUNCHER_DIR"
cat > "$LAUNCHER_DIR/hauhau" <<LAUNCHER
#!/bin/sh
# Generated by $REPO/scripts/setup.sh - re-run that after moving the repo.
exec "$REPO/.venv/bin/python" -m hauhau --config "$REPO/config.toml" "\$@"
LAUNCHER
chmod +x "$LAUNCHER_DIR/hauhau"
say "  launcher: $LAUNCHER_DIR/hauhau"

case ":$PATH:" in
    *":$LAUNCHER_DIR:"*) ;;
    *) say "  NOTE: $LAUNCHER_DIR is not on PATH. Add to ~/.zshrc:"
       say "        export PATH=\"$LAUNCHER_DIR:\$PATH\"" ;;
esac

# --- 7. smoke test ---------------------------------------------------------
if (cd /tmp && "$LAUNCHER_DIR/hauhau" --profile >/dev/null 2>&1); then
    say "  smoke test: ok (runs from any directory)"
else
    die "smoke test failed: run '$LAUNCHER_DIR/hauhau --profile' to see why"
fi

say ""
say "ready. run: hauhau \"what is in my Downloads folder?\""
say "the first turn starts llama-server itself; it stops when you exit."
